-- E14: agent visit facts for the Insight loop. Portable SQL (H2 and PostgreSQL).
--
-- One row per successful agent visit (the external task id), written inside the
-- completion transaction: model, the confidence the engine recorded, the priced
-- cost of the attempt. When the agent declares reviewed_by, the human node's
-- decision fills the review columns in its own completion transaction, so an
-- override is an outcome other than the declared acceptance. Identifiers,
-- numbers and outcome names only: no payloads, no comments, no variable values.
CREATE TABLE insight_agent_facts (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id                 VARCHAR(255) NOT NULL,
    visit_id                   VARCHAR(64)  NOT NULL,
    definition_key             VARCHAR(255) NOT NULL,
    definition_deployment_id   VARCHAR(64)  NOT NULL,
    process_instance_id        VARCHAR(64)  NOT NULL,
    agent_node                 VARCHAR(255) NOT NULL,
    model                      VARCHAR(255),
    confidence                 DOUBLE PRECISION,
    cost_usd                   NUMERIC(18,8),
    cost_unpriced              BOOLEAN DEFAULT FALSE NOT NULL,
    ended_at                   TIMESTAMP WITH TIME ZONE NOT NULL,
    review_node                VARCHAR(255),
    review_outcome             VARCHAR(255),
    overridden                 BOOLEAN,
    reviewed_at                TIMESTAMP WITH TIME ZONE
);
CREATE UNIQUE INDEX uq_insight_agent_facts_visit ON insight_agent_facts (visit_id);
CREATE INDEX idx_insight_agent_facts_node
    ON insight_agent_facts (definition_deployment_id, agent_node, ended_at);
CREATE INDEX idx_insight_agent_facts_pending_review
    ON insight_agent_facts (process_instance_id, agent_node, review_node, ended_at);

ALTER TABLE insight_findings DROP CONSTRAINT ck_insight_findings_signal;
ALTER TABLE insight_findings ADD CONSTRAINT ck_insight_findings_signal
    CHECK (signal_type IN ('FAILURE_RATE', 'LATENCY_P95', 'FALLBACK_THRASH',
                           'OVERRIDE_RATE', 'CONFIDENCE_DRIFT', 'CALIBRATION_GAP', 'COST_PER_CASE'));
