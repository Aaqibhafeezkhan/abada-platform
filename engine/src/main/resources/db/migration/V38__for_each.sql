-- E21: the items of a for-each node. Portable SQL (H2 and PostgreSQL). One row per item of one visit of the
-- node by one token; the parent instance's lock serialises everything that changes them.
CREATE TABLE for_each_items (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_instance_id   VARCHAR(255) NOT NULL,
    parent_token_id      VARCHAR(255) NOT NULL,
    activity_id          VARCHAR(255) NOT NULL,
    item_index           INT          NOT NULL,
    state                VARCHAR(16)  NOT NULL
                         CONSTRAINT ck_for_each_item_state
                         CHECK (state IN ('PENDING', 'RUNNING', 'DONE', 'FAILED')),
    item_json            TEXT,
    child_instance_id    VARCHAR(255),
    outputs_json         TEXT,
    error_code           VARCHAR(64),
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_for_each_item UNIQUE (parent_instance_id, parent_token_id, item_index)
);
CREATE INDEX idx_for_each_items_child ON for_each_items (child_instance_id);
CREATE INDEX idx_for_each_items_token ON for_each_items (parent_instance_id, parent_token_id, state);
