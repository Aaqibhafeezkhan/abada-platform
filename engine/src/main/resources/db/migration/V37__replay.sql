-- E15: replay of a proposed definition on recorded cases, and the policy that can require it before approval.
-- Portable SQL (H2 and PostgreSQL). A replay writes only these tables: it never touches an instance, a task, a
-- job, the outbox or any other runtime state.
CREATE TABLE replay_runs (
    id                   VARCHAR(36) PRIMARY KEY,
    project_id           VARCHAR(255) NOT NULL,
    proposal_id          BIGINT       NOT NULL,
    proposal_checksum    VARCHAR(64)  NOT NULL,
    definition_key       VARCHAR(255) NOT NULL,
    base_deployment_id   VARCHAR(64)  NOT NULL,
    status               VARCHAR(16)  NOT NULL
                         CONSTRAINT ck_replay_run_status
                         CHECK (status IN ('PLANNED', 'RUNNING', 'COMPLETED', 'PARTIAL', 'FAILED', 'CANCELLED')),
    requested_cases      INT          NOT NULL,
    without_inputs       INT          NOT NULL DEFAULT 0,
    budget_usd           NUMERIC(18,8),
    estimated_cost_usd   NUMERIC(18,8),
    estimate_unpriced    BOOLEAN      NOT NULL DEFAULT FALSE,
    cost_usd             NUMERIC(18,8) NOT NULL DEFAULT 0,
    cost_unpriced        BOOLEAN      NOT NULL DEFAULT FALSE,
    requested_by         VARCHAR(255) NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at           TIMESTAMP WITH TIME ZONE,
    finished_at          TIMESTAMP WITH TIME ZONE,
    purge_after          TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_replay_runs_proposal ON replay_runs (proposal_id, created_at);
CREATE INDEX idx_replay_runs_status ON replay_runs (status);

CREATE TABLE replay_cases (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                  VARCHAR(36)  NOT NULL
                            CONSTRAINT fk_replay_case_run REFERENCES replay_runs (id) ON DELETE CASCADE,
    original_instance_id    VARCHAR(255) NOT NULL,
    state                   VARCHAR(16)  NOT NULL
                            CONSTRAINT ck_replay_case_state
                            CHECK (state IN ('PENDING', 'RUNNING', 'DONE', 'NEEDS_HUMAN', 'NEEDS_EXTERNAL',
                                             'SKIPPED', 'FAILED')),
    reason                  VARCHAR(1000),
    stopped_at              VARCHAR(255),
    inputs_redacted         BOOLEAN      NOT NULL DEFAULT FALSE,
    originally_overridden   BOOLEAN,
    original_path_json      TEXT,
    replay_path_json        TEXT,
    diff_json               TEXT,
    changed                 BOOLEAN,
    last_confidence         DOUBLE PRECISION,
    tools_skipped           VARCHAR(1000),
    cost_usd                NUMERIC(18,8),
    cost_unpriced           BOOLEAN      NOT NULL DEFAULT FALSE,
    lease_owner             VARCHAR(255),
    lease_until             TIMESTAMP WITH TIME ZONE,
    started_at              TIMESTAMP WITH TIME ZONE,
    finished_at             TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_replay_cases_run ON replay_cases (run_id, id);
CREATE INDEX idx_replay_cases_claim ON replay_cases (state, lease_until);

ALTER TABLE insight_approval_policies ADD COLUMN replay_required BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE insight_approval_policies ADD COLUMN replay_min_cases INT DEFAULT 10 NOT NULL;
