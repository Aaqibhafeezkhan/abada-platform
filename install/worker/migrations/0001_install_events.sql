-- Install events recorded by the abada-install Worker (see install/README.md, "Install events").
-- One row per observed request or reported installer outcome. No raw IP address, host name, user name,
-- path, environment or key is ever stored: location comes from Cloudflare's edge metadata at request time,
-- and ip_hash is a daily-salted truncated hash used only to count unique installers per day.
CREATE TABLE IF NOT EXISTS install_events (
  id               INTEGER PRIMARY KEY AUTOINCREMENT,
  received_at      TEXT    NOT NULL,            -- UTC, ISO 8601
  kind             TEXT    NOT NULL,            -- installer_fetch | version_check | bundle_download | install_succeeded | install_failed
  version          TEXT,                        -- release version, when known
  install_id       TEXT,                        -- random id generated by the installer; not derived from the machine
  failed_step      TEXT,                        -- for install_failed: preflight|resolve|validate_key|download|verify|extract|configure|start
  os               TEXT,
  arch             TEXT,
  docker_version   TEXT,
  profile          TEXT,
  duration_s       INTEGER,
  llm_key_provided INTEGER,                     -- 0/1: whether a key was supplied, never the key
  ci               INTEGER,                     -- 0/1: reported by the installer when CI is set
  country          TEXT,
  region           TEXT,
  city             TEXT,
  continent        TEXT,
  timezone         TEXT,
  asn              INTEGER,
  as_org           TEXT,
  ip_hash          TEXT,                        -- daily-salted, truncated; NULL when no salt is configured
  user_agent       TEXT
);
CREATE INDEX IF NOT EXISTS idx_install_events_time    ON install_events (received_at);
CREATE INDEX IF NOT EXISTS idx_install_events_kind    ON install_events (kind, received_at);
CREATE INDEX IF NOT EXISTS idx_install_events_version ON install_events (version);
CREATE INDEX IF NOT EXISTS idx_install_events_country ON install_events (country);
CREATE INDEX IF NOT EXISTS idx_install_events_ip      ON install_events (ip_hash, received_at);
